a = 10
b = 50

#Suma
resultado = a + b
print(resultado)

#Resta
resultado = a - b
print(resultado)

#Multiplicacion
resultado = a * b
print(resultado)

#Division
resultado = a / b
print(resultado)

#Division exacta (descarta decimales) 10 / 50 = 0.2 con doble // seria 0 
resultado = a // b
print(resultado)

#Modulo (Resto de la division) lo que sobra entre dividir 10 / 50 no es exacto el resto sigue siendo 10
resultado = a % b
print(resultado)

#Potencia el 10 elevado a la 50
resultado = a ** b
print(resultado)

