numero1 = 20

#Incrementador (+= es lo mismo que num = num + algo)
numero1 += 5 # numero1 = numero1 + 5
print(numero1)

#Decrementador 
numero1 -= 10
print(numero1)

#Multiplicador
numero1 *= 4
print(numero1)

#Divisor
numero1 /= 4
print(numero1)

#Modulador
numero1 %= 4
print(numero1)

#Potenciometro
numero1 **= 4
print(numero1)
